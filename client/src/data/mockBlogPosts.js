// Helper to create dates
const now = new Date();
const createDate = (daysOffset, hours = 0, minutes = 0) => {
  const date = new Date(now);
  date.setDate(date.getDate() + daysOffset);
  date.setHours(hours, minutes, 0, 0);
  return date.toISOString();
};

